package com.darija.learn.data;

public class VocabItem {
    public final String darija;
    public final String arabic;
    public final String french;
    public final String english;

    public VocabItem(String darija, String arabic, String french, String english) {
        this.darija = darija;
        this.arabic = arabic;
        this.french = french;
        this.english = english;
    }
}
